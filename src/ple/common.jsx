// ---- Selectors -------------------------------------------------------------

export const isComplete = (s) => s === 'merged';

/** Everything the Problems / plan / campaign screens need about one group. */
export function groupView(state, g) {
  const event = g.pleId ? state.ple.events.find((e) => e.id === g.pleId) : null;
  const findings = state.findings.filter((f) => g.findingIds.includes(f.id));
  const live = findings.filter((f) => f.status !== 'Dismissed');
  const open = live.filter((f) => !f.status.startsWith('Resolved'));
  const td = event ? event.td : live.find((f) => f.transformation)?.transformation ?? null;
  const severity = ['High', 'Medium', 'Low'].find((s) => live.some((f) => f.severity === s)) ?? 'Low';
  const repos = [...new Set(live.map((f) => f.repo))];
  const covered = new Set(live.flatMap((f) => f.functions ?? []));
  const resources = event?.resources ?? [];
  // Split groups only claim the resources their findings cover.
  const isWhole = !g.splitFrom;
  const groupResources = isWhole ? resources : resources.filter((r) => covered.has(r.name));
  const found = groupResources.filter((r) => r.repo && repos.includes(r.repo));
  const notFound = isWhole ? resources.filter((r) => !r.repo) : [];
  const campaigns = state.ple.campaigns.filter((c) => c.groups.some((x) => x.id === g.id));
  const runs = campaigns.flatMap((c) => c.repos.filter((r) => r.groupId === g.id).map((r) => ({ ...r, campaignId: c.id })));
  const merged = repos.filter((repo) => runs.some((r) => r.repo === repo && isComplete(r.status)));
  const progress = repos.length ? Math.round((merged.length / repos.length) * 100) : 0;
  const linked = repos.map((r) => repoFixture(g.pleId, r)).filter((fx) => fx?.linked && repos.includes(fx.linked));
  const linkedPairs = linked.length ? [[linked[0].repo, linked[0].linked]] : [];
  let safety;
  if (g.type === 'C' && g.skill?.status !== 'ready') safety = { tone: 'warn', label: 'Skill not yet tested', detail: 'A specialized skill must pass build and test on held-out repositories before it runs on your code.' };
  else if (linkedPairs.length) safety = { tone: 'warn', label: `${linkedPairs.length} warning: linked repos`, detail: `${linkedPairs[0][0]} and ${linkedPairs[0][1]} depend on each other. They'll run in sequence.`, pairs: linkedPairs };
  else safety = { tone: 'ok', label: 'Meets the bar' };
  const remediating = !event && open.some((f) => f.status === 'In remediation');
  const status = event ? (campaigns.length === 0 ? 'Not started' : progress === 100 ? 'Complete' : 'In progress') : remediating ? 'In progress' : open.length ? 'Not started' : 'Complete';
  return {
    event, findings, live, open, td, severity, repos, resources: groupResources, found, notFound, campaigns, runs, merged, progress, safety, status,
    days: event ? daysLeft(event.changeDate) : null,
    recommended: !event ? td ?? 'Custom transformation' : event.td ? `${event.tdLabel} (AWS-managed)` : g.skill?.status === 'ready' ? 'Specialized skill (tested)' : 'Specialized skill (proposed)',
  };
}

export const groupTypeLabel = (t) => GROUP_TYPES[t];

export function deepLink(event, account) {
  const q = new URLSearchParams({ event: event.arn, account, source: 'health' });
  if (event.td) q.set('td', event.td);
  else q.set('skill', 'generate');
  return `#/app/ple/welcome?${q}`;
}

export const remediationLine = (event) =>
  event.td ? `${event.tdLabel} (AWS-managed transformation)` : 'Specialized skill, generated by AWS Transform for this change';

// ---- Components ------------------------------------------------------------

export function PleTag() {
  return <span className="ple-tag" title="Planned lifecycle event (PLE), from AWS Health">PLE</span>;
}

export function ChangeDate({ iso, short }) {
  const d = daysLeft(iso);
  const tone = d <= 100 ? 'soon' : '';
  return (
    <span className={`change-date ${tone}`}>
      {fmtDate(iso)} · {d} days{short ? '' : ' left'}
    </span>
  );
}

export function SafetyBar({ safety }) {
  return safety.tone === 'ok' ? (
    <span className="status status-success"><Icon.check /> {safety.label}</span>
  ) : (
    <span className="status status-warning"><Icon.warn /> {safety.label}</span>
  );
}

export function Stepper({ step }) {
  const steps = ['Connect repositories', 'Allow AWS Health access', 'Find affected code'];
  return (
    <ol className="steps ple-steps">
      {steps.map((s, i) => (
        <li key={s} className={i + 1 < step ? 'done' : i + 1 === step ? 'current' : ''}>
          {i + 1 < step ? <Icon.check /> : <span className="step-num">{i + 1}</span>} {s}
        </li>
      ))}
    </ol>
  );
}

export function ContextStrip({ event }) {
  if (!event) return null;
  const n = event.resources.length;
  return (
    <div className="context-strip">
      <PleTag /> <strong>{shortTitle(event)}</strong> · {n} {unit(event, n)} · due {fmtDate(event.changeDate)}
    </div>
  );
}

export const shortTitle = (e) =>
  ({ 'lambda-py39': 'Lambda Python 3.9', 'lambda-node16': 'Lambda Node.js 16', 'rds-pg14': 'RDS for PostgreSQL 14', 'cache-redis6': 'ElastiCache Redis OSS 6' })[e.id] ?? e.title;

export const unit = (e, n) => {
  const u = e.service === 'Lambda' ? 'function' : e.service === 'RDS' ? 'DB instance' : e.service === 'ElastiCache' ? 'cluster' : 'resource';
  return n === 1 ? u : `${u}s`;
};

export function Ring({ value, total, label }) {
  const r = 26;
  const c = 2 * Math.PI * r;
  const pct = total ? value / total : 0;
  return (
    <div className="ring">
      <svg viewBox="0 0 64 64" width="64" height="64" aria-hidden>
        <circle cx="32" cy="32" r={r} fill="none" stroke="#e9ebed" strokeWidth="7" />
        <circle cx="32" cy="32" r={r} fill="none" stroke="#037f0c" strokeWidth="7" strokeDasharray={`${pct * c} ${c}`} transform="rotate(-90 32 32)" strokeLinecap="round" />
      </svg>
      <div>
        <div className="ring-value">{value} of {total}</div>
        <div className="muted small">{label}</div>
      </div>
    </div>
  );
}

export function Meter({ value, total, label, tone = 'success' }) {
  const pct = total ? (value / total) * 100 : 0;
  return (
    <div className="meter">
      <div className="meter-label">
        <span>{label}</span>
        <strong>{value} of {total}</strong>
      </div>
      <div className="meter-track">
        <div className={`meter-fill ${tone}`} style={{ width: `${pct}%` }} />
      </div>
    </div>
  );
}

